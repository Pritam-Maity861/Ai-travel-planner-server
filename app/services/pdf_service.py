class NumberedCanvas(canvas.Canvas):
    """Canvas that performs a two-pass calculation of total page numbers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running header (on pages > 1)
        if self._pageNumber > 1:
            self.drawString(
                54,
                11 * inch - 36,
                "Aetheria AI Travel Architect • Official Master Itinerary",
            )
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 11 * inch - 42, 8.5 * inch - 54, 11 * inch - 42)

        # Running footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 54, 30, footer_text)
        self.drawString(
            54,
            30,
            "Confidential • Generated by Autonomous Multi-Agent System (FastAPI & LangGraph)",
        )
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 42, 8.5 * inch - 54, 42)

        self.restoreState()


def sanitize_text_for_pdf(text: str) -> str:
    """Normalize unicode characters missing from standard Type-1 Helvetica font."""
    if not text:
        return ""
    replacements = {
        # Indian Rupee and currencies
        "\u20b9": "INR ",
        "\u20ac": "EUR ",
        "\u00a3": "GBP ",
        "\u00a5": "JPY ",
        # Math & Relations
        "\u2248": "~",  # almost equal to
        "\u223c": "~",
        "\u2243": "~",
        "\u2245": "~",
        "\u2260": "!=",
        "\u2264": "<=",
        "\u2265": ">=",
        "\u00b1": "+/-",
        "\u00d7": "x",
        "\u00f7": "/",
        # Dashes & Hyphens
        "\u2010": "-",
        "\u2011": "-",  # non-breaking hyphen
        "\u2012": "-",  # figure dash
        "\u2013": "-",  # en dash
        "\u2014": " - ",  # em dash
        "\u2015": " - ",  # horizontal bar
        "\u2212": "-",  # minus sign
        # Quotes & Punctuation
        "\u2018": "'",
        "\u2019": "'",
        "\u201a": ",",
        "\u201b": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u201e": '"',
        "\u2026": "...",
        # Spaces
        "\u202f": " ",  # narrow no-break space
        "\u00a0": " ",  # non-breaking space
        "\u200b": "",  # zero-width space
        "\u200c": "",
        "\u200d": "",
        "\ufeff": "",
        # Bullets & Shapes
        "\u2022": "&bull;",
        "\u25e6": "&bull;",
        "\u25aa": "&bull;",
        "\u25ab": "&bull;",
        "\u25cf": "&bull;",
        "\u25cb": "&bull;",
        "\u25a0": "-",
        "\u25a1": "-",
        # Arrows & Checkmarks
        "\u279c": "-&gt;",  # right arrow
        "\u2794": "-&gt;",
        "\u2192": "-&gt;",
        "\u27a1": "-&gt;",
        "\u2190": "&lt;-",
        "\u2194": "&lt;-&gt;",
        "\u25b6": "-&gt;",
        "\u25c0": "&lt;-",
        "\u2714": "v",
        "\u2713": "v",
        "\u2716": "x",
        "\u2717": "x",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def clean_markdown_for_pdf(text: str) -> str:
    """Strip or format basic markdown characters into XML-safe tags for ReportLab."""
    if not text:
        return ""
    text = sanitize_text_for_pdf(text)

    # 1. Normalize line break tags into placeholder before escaping
    text = re.sub(r"(?i)<br\s*/?>", "___RL_BR_TAG___", text)

    # 2. Convert standard HTML emphasis to markdown delimiters
    text = re.sub(r"(?i)</?strong>", "**", text)
    text = re.sub(r"(?i)</?b>", "**", text)
    text = re.sub(r"(?i)</?em>", "*", text)
    text = re.sub(r"(?i)</?i>", "*", text)

    # 3. Strip any other unsupported HTML tags
    text = re.sub(r"<[^>]+>", " ", text)

    # 4. XML escape (preserving &bull;, &rarr;, &amp;, &lt;, &gt;)
    text = re.sub(r"&(?!(amp|lt|gt|quot|bull|rarr);)", "&amp;", text)
    text = text.replace("<", "&lt;").replace(">", "&gt;")

    # 5. Bold **text**
    text = re.sub(r"\*\*(.*?)\*\*", r"<b>\1</b>", text)
    # 6. Italic *text*
    text = re.sub(r"(?<!\*)\*([^\*]+?)\*(?!\*)", r"<i>\1</i>", text)
    # 7. Inline code `code`
    text = re.sub(r"`([^`]+)`", r"<font face='Courier'>\1</font>", text)

    # 8. Restore line breaks as valid ReportLab self-closing <br/>
    text = text.replace("___RL_BR_TAG___", "<br/>")

    return text.strip()


def render_markdown_flowables(
    text: str,
    body_style: ParagraphStyle,
    bullet_style: ParagraphStyle,
    h2_style: ParagraphStyle,
    table_header_style: ParagraphStyle,
    table_cell_style: ParagraphStyle,
    primary_color: colors.Color,
    default_as_bullet: bool = False,
) -> list[Any]:
    """Parse mixed markdown (paragraphs, tables, bullet points, headers) into styled Flowables."""
    if not text:
        return []

    # Replace HTML line break tags with \n so joined bullet points or lines split cleanly
    text = re.sub(r"(?i)<br\s*/?>", "\n", text)

    flowables: list[Any] = []
    lines = text.strip().split("\n")
    i = 0
    para_lines: list[str] = []

    def flush_para():
        nonlocal para_lines
        if para_lines:
            joined = " ".join(p.strip() for p in para_lines if p.strip())
            if joined:
                cleaned = clean_markdown_for_pdf(joined)
                flowables.append(Paragraph(cleaned, body_style))
                flowables.append(Spacer(1, 4))
            para_lines = []

    while i < len(lines):
        line = lines[i].strip()

        # 1. Blank line -> flush current paragraph
        if not line:
            flush_para()
            i += 1
            continue

        # 2. Markdown table detection: lines with '|'
        if line.startswith("|") and line.endswith("|") and line.count("|") >= 2:
            flush_para()
            table_lines: list[str] = []
            while (
                i < len(lines)
                and lines[i].strip().startswith("|")
                and lines[i].strip().endswith("|")
            ):
                table_lines.append(lines[i].strip())
                i += 1

            table_data: list[list[Paragraph]] = []
            for r_line in table_lines:
                stripped_cells = [c.strip() for c in r_line.strip("|").split("|")]
                # Skip divider row like |---|---|
                if all(re.match(r"^:?-+:?$", c) for c in stripped_cells if c):
                    continue

                row_cells: list[Paragraph] = []
                is_header = len(table_data) == 0
                cell_style = table_header_style if is_header else table_cell_style

                for cell in stripped_cells:
                    cleaned_cell = clean_markdown_for_pdf(cell)
                    if is_header and not cleaned_cell.startswith("<b>"):
                        cleaned_cell = f"<b>{cleaned_cell}</b>"
                    row_cells.append(Paragraph(cleaned_cell, cell_style))

                if row_cells:
                    table_data.append(row_cells)

            if table_data:
                num_cols = max(len(row) for row in table_data)
                for row in table_data:
                    while len(row) < num_cols:
                        row.append(Paragraph("", table_cell_style))

                total_width = 7.0 * inch
                col_w = [total_width / num_cols] * num_cols
                t = Table(table_data, colWidths=col_w)
                t.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), primary_color),
                            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ]
                    )
                )
                flowables.append(t)
                flowables.append(Spacer(1, 8))
            continue

        # 3. Bullet points: * or - or • or 1.
        bullet_match = re.match(r"^(\*|-|•|\d+\.)\s*(.+)$", line)
        if bullet_match:
            flush_para()
            bullet_content = bullet_match.group(2).strip()
            bullet_content = re.sub(r"^(•|\*|-)\s*", "", bullet_content)
            cleaned_bullet = clean_markdown_for_pdf(bullet_content)
            flowables.append(Paragraph(f"&bull; {cleaned_bullet}", bullet_style))
            i += 1
            continue

        # 4. Heading: # or ## or ###
        heading_match = re.match(r"^(#{1,4})\s+(.+)$", line)
        if heading_match:
            flush_para()
            heading_content = heading_match.group(2)
            flowables.append(Paragraph(clean_markdown_for_pdf(heading_content), h2_style))
            i += 1
            continue

        # 5. Default as bullet mode (for tips, recs, assumptions lists)
        if default_as_bullet:
            flush_para()
            cleaned_line = re.sub(r"^(•|\*|-|\d+\.)\s*", "", line)
            cleaned_bullet = clean_markdown_for_pdf(cleaned_line)
            flowables.append(Paragraph(f"&bull; {cleaned_bullet}", bullet_style))
            i += 1
            continue

        # 6. Normal text line -> accumulate into paragraph
        para_lines.append(line)
        i += 1

    flush_para()
    return flowables


def generate_trip_pdf(
    state_values: dict[str, Any], thread_id: str, is_preview: bool = False
) -> bytes:
    """Generate a high-quality, comprehensive travel master plan PDF from state values."""
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    primary_color = colors.HexColor("#4f46e5")  # Indigo
    dark_neutral = colors.HexColor("#0f172a")  # Slate 900
    text_color = colors.HexColor("#334155")  # Slate 700

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=dark_neutral,
        spaceAfter=4,
    )

    subtitle_style = ParagraphStyle(
        "DocSubTitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=14,
    )

    h1_style = ParagraphStyle(
        "SectionH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=primary_color,
        spaceBefore=14,
        spaceAfter=8,
        keepWithNext=True,
    )

    h2_style = ParagraphStyle(
        "SectionH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=dark_neutral,
        spaceBefore=8,
        spaceAfter=4,
        keepWithNext=True,
    )

    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=13.5,
        textColor=text_color,
        spaceAfter=6,
    )

    bullet_style = ParagraphStyle(
        "DocBullet",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=text_color,
        leftIndent=12,
        spaceAfter=3,
    )

    table_header_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=colors.white,
    )

    table_cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=dark_neutral,
    )

    story: list[Any] = []

    if is_preview:
        preview_notice_style = ParagraphStyle(
            "PreviewNotice",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#92400e"),
            alignment=1,
        )
        notice_text = "DRAFT ITINERARY FOR HUMAN REVIEW &bull; NOT YET FINALIZED"
        preview_table = Table(
            [[Paragraph(notice_text, preview_notice_style)]],
            colWidths=[7.0 * inch],
        )
        preview_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fef3c7")),
                    ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#f59e0b")),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(preview_table)
        story.append(Spacer(1, 10))

    # 1. Header & Title Block
    constraints = state_values.get("trip_constraints", {})
    destination = constraints.get("destination") or "Exclusive Destination"
    origin = constraints.get("origin") or "Origin"
    duration = constraints.get("duration_days") or "Multi-Day"
    travelers = constraints.get("travelers") or 1
    budget = constraints.get("budget")
    currency = constraints.get("currency", "INR")
    if not currency or currency in ("₹", "Rs", "Rs."):
        currency = "INR"

    plan_title = f"Travel Master Plan: {clean_markdown_for_pdf(destination)}"
    story.append(Paragraph(plan_title, title_style))
    ref_text = f"Curated by Aetheria Multi-Agent AI System • Ref: <code>{thread_id[:8]}</code>"
    story.append(Paragraph(ref_text, subtitle_style))
    story.append(
        HRFlowable(
            width="100%",
            thickness=1.5,
            color=primary_color,
            spaceBefore=0,
            spaceAfter=12,
        )
    )

    # 2. Key Trip Overview Table
    adults = constraints.get("adults") or 1
    children = constraints.get("children") or 0
    start_date = constraints.get("start_date")
    end_date = constraints.get("end_date")
    if start_date and end_date:
        dates_str = f"{start_date} to {end_date}"
    elif start_date:
        dates_str = f"From {start_date} ({duration} Days)"
    else:
        dates_str = f"{duration} Days (Flexible Window)"

    food_pref = constraints.get("food_preference") or "Standard / Any"

    adult_lbl = f"{adults} Adult{'s' if adults > 1 else ''}"
    child_lbl = f", {children} Child{'ren' if children != 1 else ''}" if children > 0 else ""
    travelers_display = f"{travelers} Total ({adult_lbl}{child_lbl})"

    overview_data = [
        [
            Paragraph("<b>Origin:</b>", table_cell_style),
            Paragraph(origin, table_cell_style),
            Paragraph("<b>Destination:</b>", table_cell_style),
            Paragraph(destination, table_cell_style),
        ],
        [
            Paragraph("<b>Duration:</b>", table_cell_style),
            Paragraph(f"{duration} Days", table_cell_style),
            Paragraph("<b>Travelers:</b>", table_cell_style),
            Paragraph(travelers_display, table_cell_style),
        ],
        [
            Paragraph("<b>Target Budget:</b>", table_cell_style),
            Paragraph(
                f"{currency} {budget:,.0f}" if budget else "Flexible / Unstated",
                table_cell_style,
            ),
            Paragraph("<b>Dates / Window:</b>", table_cell_style),
            Paragraph(dates_str, table_cell_style),
        ],
        [
            Paragraph("<b>Dining Preference:</b>", table_cell_style),
            Paragraph(food_pref, table_cell_style),
            Paragraph("<b>Transit Scope:</b>", table_cell_style),
            Paragraph("Flights & Railway Intelligence", table_cell_style),
        ],
    ]

    prefs = constraints.get("preferences") or []
    if prefs:
        overview_data.append(
            [
                Paragraph("<b>Preferences:</b>", table_cell_style),
                Paragraph(", ".join(prefs), table_cell_style),
                Paragraph("", table_cell_style),
                Paragraph("", table_cell_style),
            ]
        )

    col_w = [1.3 * inch, 2.2 * inch, 1.3 * inch, 2.2 * inch]
    overview_table = Table(overview_data, colWidths=col_w)
    overview_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    story.append(overview_table)
    story.append(Spacer(1, 14))

    # 3. Flight Intelligence Section
    flights = state_values.get("flight_results", {})
    if flights and isinstance(flights, dict):
        story.append(Paragraph("1. Flight & Aviation Intelligence", h1_style))
        summary = flights.get("summary")
        has_summary_table = False
        if summary:
            if "|" in summary and summary.count("|") >= 4:
                has_summary_table = True
            story.extend(
                render_markdown_flowables(
                    summary,
                    body_style=body_style,
                    bullet_style=bullet_style,
                    h2_style=h2_style,
                    table_header_style=table_header_style,
                    table_cell_style=table_cell_style,
                    primary_color=primary_color,
                )
            )

        if not has_summary_table:
            raw_val = flights.get("raw")
            raw_flights = []
            if isinstance(raw_val, list):
                raw_flights = raw_val
            elif isinstance(raw_val, dict):
                raw_flights = raw_val.get("flights") or raw_val.get("data") or []

            if raw_flights and isinstance(raw_flights, list):
                f_table_data = [
                    [
                        Paragraph("<b>Airline</b>", table_header_style),
                        Paragraph("<b>Flight #</b>", table_header_style),
                        Paragraph("<b>Scheduled Departure</b>", table_header_style),
                        Paragraph("<b>Scheduled Arrival</b>", table_header_style),
                    ]
                ]
                for f in raw_flights[:4]:
                    if isinstance(f, dict):
                        airline = str(f.get("airline", "Scheduled"))
                        flight_num = str(f.get("flight", "N/A"))
                        dep = str(f.get("departure", "TBD"))
                        arr = str(f.get("arrival", "TBD"))
                    else:
                        airline = str(f)
                        flight_num = "N/A"
                        dep = "TBD"
                        arr = "TBD"

                    f_table_data.append(
                        [
                            Paragraph(clean_markdown_for_pdf(airline), table_cell_style),
                            Paragraph(clean_markdown_for_pdf(flight_num), table_cell_style),
                            Paragraph(clean_markdown_for_pdf(dep), table_cell_style),
                            Paragraph(clean_markdown_for_pdf(arr), table_cell_style),
                        ]
                    )
                f_col_w = [2.2 * inch, 1.3 * inch, 1.7 * inch, 1.8 * inch]
                f_table = Table(f_table_data, colWidths=f_col_w)
                f_table.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), primary_color),
                            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ]
                    )
                )
                story.append(f_table)
        story.append(Spacer(1, 12))

    # Rail / Train Transit Section (WorldTrainMap)
    trains = state_values.get("train_results", {})
    if trains and isinstance(trains, dict):
        story.append(Paragraph("2. Rail Transit Intelligence (WorldTrainMap)", h1_style))
        t_summary = trains.get("summary")
        if t_summary:
            story.extend(
                render_markdown_flowables(
                    t_summary,
                    body_style=body_style,
                    bullet_style=bullet_style,
                    h2_style=h2_style,
                    table_header_style=table_header_style,
                    table_cell_style=table_cell_style,
                    primary_color=colors.HexColor("#0f766e"),
                )
            )
        story.append(Spacer(1, 12))

    # 4. Accommodations / Hotels Section
    hotels = state_values.get("hotel_results", {})
    if hotels and isinstance(hotels, dict):
        story.append(Paragraph("2. Curated Accommodations & Stays", h1_style))
        hotel_summary = hotels.get("summary")
        has_hotel_table = False
        if hotel_summary:
            if "|" in hotel_summary and hotel_summary.count("|") >= 4:
                has_hotel_table = True
            story.extend(
                render_markdown_flowables(
                    hotel_summary,
                    body_style=body_style,
                    bullet_style=bullet_style,
                    h2_style=h2_style,
                    table_header_style=table_header_style,
                    table_cell_style=table_cell_style,
                    primary_color=colors.HexColor("#4338ca"),
                )
            )

        if not has_hotel_table:
            hotel_list = hotels.get("hotels", [])
            if hotel_list and isinstance(hotel_list, list):
                h_table_data = [
                    [
                        Paragraph("<b>Property Name</b>", table_header_style),
                        Paragraph("<b>Area / Neighborhood</b>", table_header_style),
                        Paragraph("<b>Price Est.</b>", table_header_style),
                        Paragraph("<b>Why Recommended</b>", table_header_style),
                    ]
                ]
                for h in hotel_list:
                    if isinstance(h, dict):
                        h_name = str(h.get("name", "Hotel"))
                        h_area = str(h.get("area", "Prime"))
                        h_price = str(h.get("approx_price") or "Market Rate")
                        h_why = str(h.get("why_it_fits", "Curated"))
                    else:
                        h_name = str(h)
                        h_area = "Prime"
                        h_price = "Market Rate"
                        h_why = "Curated"

                    h_table_data.append(
                        [
                            Paragraph(f"<b>{clean_markdown_for_pdf(h_name)}</b>", table_cell_style),
                            Paragraph(clean_markdown_for_pdf(h_area), table_cell_style),
                            Paragraph(clean_markdown_for_pdf(h_price), table_cell_style),
                            Paragraph(clean_markdown_for_pdf(h_why), table_cell_style),
                        ]
                    )
                h_col_w = [1.8 * inch, 1.5 * inch, 1.3 * inch, 2.4 * inch]
                h_table = Table(h_table_data, colWidths=h_col_w)
                h_table.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4338ca")),
                            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                            ("TOPPADDING", (0, 0), (-1, -1), 5),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                        ]
                    )
                )
                story.append(h_table)
        story.append(Spacer(1, 12))

    # 5. Weather & Climate Section
    weather = state_values.get("weather_info", {})
    if weather and isinstance(weather, dict) and weather.get("summary"):
        story.append(Paragraph("3. Weather Forecast & Packing Guidelines", h1_style))
        story.extend(
            render_markdown_flowables(
                weather["summary"],
                body_style=body_style,
                bullet_style=bullet_style,
                h2_style=h2_style,
                table_header_style=table_header_style,
                table_cell_style=table_cell_style,
                primary_color=colors.HexColor("#0284c7"),
            )
        )
        story.append(Spacer(1, 12))

    # 6. Detailed Day-by-Day Itinerary Plan
    itinerary = state_values.get("itinerary_plan", {})
    days = itinerary.get("days", [])
    if days:
        story.append(Paragraph("4. Detailed Day-by-Day Itinerary", h1_style))
        for d in days:
            day_num = d.get("day", 1)
            day_title = d.get("title", f"Day {day_num}")
            story.append(Paragraph(f"Day {day_num}: {clean_markdown_for_pdf(day_title)}", h2_style))

            day_table_data = [
                [
                    Paragraph("<b>Morning:</b>", table_cell_style),
                    Paragraph(clean_markdown_for_pdf(d.get("morning", "")), table_cell_style),
                ],
                [
                    Paragraph("<b>Afternoon:</b>", table_cell_style),
                    Paragraph(clean_markdown_for_pdf(d.get("afternoon", "")), table_cell_style),
                ],
                [
                    Paragraph("<b>Evening:</b>", table_cell_style),
                    Paragraph(clean_markdown_for_pdf(d.get("evening", "")), table_cell_style),
                ],
            ]
            t_notes = d.get("transport_notes")
            if t_notes:
                day_table_data.append(
                    [
                        Paragraph("<b>Transport:</b>", table_cell_style),
                        Paragraph(clean_markdown_for_pdf(t_notes), table_cell_style),
                    ]
                )

            day_table = Table(day_table_data, colWidths=[1.2 * inch, 5.8 * inch])
            day_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ]
                )
            )
            story.append(KeepTogether([day_table, Spacer(1, 6)]))

        # Tips
        tips = itinerary.get("tips", [])
        if tips:
            story.append(Spacer(1, 4))
            story.append(Paragraph("<b>Traveler Tips & Recommendations:</b>", h2_style))
            tip_items = [tips] if isinstance(tips, str) else tips
            for tip in tip_items:
                if not tip:
                    continue
                story.extend(
                    render_markdown_flowables(
                        str(tip),
                        body_style=body_style,
                        bullet_style=bullet_style,
                        h2_style=h2_style,
                        table_header_style=table_header_style,
                        table_cell_style=table_cell_style,
                        primary_color=colors.HexColor("#0284c7"),
                        default_as_bullet=True,
                    )
                )
        story.append(Spacer(1, 12))

    # 7. Budget Analysis & Breakdown
    budget_data = state_values.get("budget_analysis", {})
    if budget_data and isinstance(budget_data, dict):
        story.append(Paragraph("5. Expense Breakdown & Financial Overview", h1_style))
        total_est = budget_data.get("total_estimate") or 0
        within = budget_data.get("within_budget")
        if within is True:
            within_label = "Within Budget"
        elif within is False:
            within_label = "Exceeds Stated Budget"
        else:
            within_label = "Unconstrained"

        f_est = budget_data.get("flights_estimate") or 0
        h_est = budget_data.get("hotel_estimate") or 0
        ft_est = budget_data.get("food_and_transport_estimate") or 0
        a_est = budget_data.get("activities_estimate") or 0

        b_table_data = [
            [
                Paragraph("<b>Expense Category</b>", table_header_style),
                Paragraph("<b>Estimated Amount</b>", table_header_style),
                Paragraph("<b>Notes / Coverage</b>", table_header_style),
            ],
            [
                Paragraph("Flight Travel", table_cell_style),
                Paragraph(f"{currency} {f_est:,.0f}", table_cell_style),
                Paragraph("Roundtrip route estimates", table_cell_style),
            ],
            [
                Paragraph("Accommodations", table_cell_style),
                Paragraph(f"{currency} {h_est:,.0f}", table_cell_style),
                Paragraph("Curated stays for entire group", table_cell_style),
            ],
            [
                Paragraph("Food & Transit", table_cell_style),
                Paragraph(f"{currency} {ft_est:,.0f}", table_cell_style),
                Paragraph("Daily meals and local transport", table_cell_style),
            ],
            [
                Paragraph("Activities & Sightseeing", table_cell_style),
                Paragraph(f"{currency} {a_est:,.0f}", table_cell_style),
                Paragraph("Entry passes and excursions", table_cell_style),
            ],
            [
                Paragraph("<b>Total Estimated Outlay</b>", table_cell_style),
                Paragraph(f"<b>{currency} {total_est:,.0f}</b>", table_cell_style),
                Paragraph(f"<b>Status: {within_label}</b>", table_cell_style),
            ],
        ]

        b_table = Table(b_table_data, colWidths=[2.2 * inch, 2.0 * inch, 2.8 * inch])
        b_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f766e")),  # Teal
                    ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#f0fdf4")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(b_table)

        recs = budget_data.get("recommendations", [])
        if recs:
            story.append(Spacer(1, 4))
            story.append(Paragraph("<b>Cost Optimization Recommendations:</b>", h2_style))
            rec_items = [recs] if isinstance(recs, str) else recs
            for r in rec_items:
                if not r:
                    continue
                story.extend(
                    render_markdown_flowables(
                        str(r),
                        body_style=body_style,
                        bullet_style=bullet_style,
                        h2_style=h2_style,
                        table_header_style=table_header_style,
                        table_cell_style=table_cell_style,
                        primary_color=colors.HexColor("#0f766e"),
                        default_as_bullet=True,
                    )
                )

        assumptions = budget_data.get("assumptions", [])
        if assumptions:
            story.append(Spacer(1, 4))
            story.append(Paragraph("<b>Underlying Assumptions:</b>", h2_style))
            assump_items = [assumptions] if isinstance(assumptions, str) else assumptions
            for a in assump_items:
                if not a:
                    continue
                story.extend(
                    render_markdown_flowables(
                        str(a),
                        body_style=body_style,
                        bullet_style=bullet_style,
                        h2_style=h2_style,
                        table_header_style=table_header_style,
                        table_cell_style=table_cell_style,
                        primary_color=colors.HexColor("#0f766e"),
                        default_as_bullet=True,
                    )
                )

    doc.build(story, canvasmaker=NumberedCanvas)
